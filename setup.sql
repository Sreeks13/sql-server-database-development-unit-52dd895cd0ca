IF DB_ID(N'TaxiDB') IS NULL
BEGIN
    CREATE DATABASE TaxiDB;
END
GO

USE TaxiDB;
GO

IF OBJECT_ID(N'dbo.Trips', N'U') IS NOT NULL
    DROP TABLE dbo.Trips;
GO

CREATE TABLE dbo.Trips
(
    TripID INT IDENTITY(1,1) NOT NULL
        CONSTRAINT PK_Trips PRIMARY KEY,

    PassengerName NVARCHAR(100) NOT NULL,
    DriverName NVARCHAR(100) NOT NULL,

    DistanceKm DECIMAL(10,2) NOT NULL,
    FarePerKm DECIMAL(10,2) NOT NULL,
    Fare DECIMAL(10,2) NOT NULL,

    TripDate DATETIME2 NOT NULL
        CONSTRAINT DF_Trips_TripDate DEFAULT SYSUTCDATETIME()
);
GO
