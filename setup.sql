IF DB_ID('TaxiDB') IS NULL
    CREATE DATABASE TaxiDB;
GO

USE TaxiDB;
GO

IF OBJECT_ID('dbo.Trips', 'U') IS NOT NULL
    DROP TABLE dbo.Trips;
GO

CREATE TABLE dbo.Trips
(
    TripID INT IDENTITY(1,1) PRIMARY KEY,
    PassengerName NVARCHAR(100) NOT NULL,
    DriverName NVARCHAR(100) NOT NULL,
    DistanceKm DECIMAL(10,2) NOT NULL,
    FarePerKm DECIMAL(10,2) NOT NULL,
    Fare DECIMAL(10,2) NOT NULL,
    TripDate DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);
GO
